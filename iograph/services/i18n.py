    def __init__(self, settings: AppSettings) -> None:
        self._settings = settings
        self._mode = self._normalize_mode(
            self._settings.get_str(SettingsKeys.OPTION_LANGUAGE, self.AUTO_MODE)
        )

    @classmethod
    def _normalize_mode(cls, mode: str) -> str:
        normalized = (mode or "").strip()
        if normalized == cls.AUTO_MODE:
            return normalized
        if normalized in cls.SUPPORTED_LANGUAGES:
            return normalized
        lower = normalized.lower()
        if lower in cls.SUPPORTED_LANGUAGES:
            return lower
        return cls.AUTO_MODE

    def current_mode(self) -> str:
        return self._mode

    def set_language_mode(self, mode: str) -> str:
        self._mode = self._normalize_mode(mode)
        self._settings.set(SettingsKeys.OPTION_LANGUAGE, self._mode, sync=True)
        return self._mode

    def effective_language(self) -> str:
        if self._mode != self.AUTO_MODE:
            return self._mode
        return self._resolve_system_language()

    def language_menu_options(self) -> list[tuple[str, str]]:
        options = [(code, self.LANGUAGE_LABELS.get(code, code)) for code in self.SUPPORTED_LANGUAGES]
        options.sort(key=lambda item: item[1].casefold())
        return [(self.AUTO_MODE, self.tr("lang.auto_system"))] + options

    @classmethod
    def translation_ids(cls) -> tuple[str, ...]:
        return tuple(cls._KEY_TO_SOURCE.keys())

    @classmethod
    def missing_translation_ids(cls, language: str) -> list[str]:
        if language == cls.DEFAULT_LANGUAGE:
            return []
        source_map = cls._TRANSLATIONS.get(language, {})
        extra_map = cls._EXTRA_TRANSLATIONS.get(language, {})
        missing: list[str] = []
        for key, source in cls._KEY_TO_SOURCE.items():
            if key in cls._OPTIONAL_TRANSLATION_IDS:
                continue
            if source not in source_map and source not in extra_map:
                missing.append(key)
        return missing

    @classmethod
    def translation_coverage_report(cls) -> dict[str, dict[str, int]]:
        total = len([k for k in cls._KEY_TO_SOURCE if k not in cls._OPTIONAL_TRANSLATION_IDS])
        report: dict[str, dict[str, int]] = {}
        for lang in cls.SUPPORTED_LANGUAGES:
            missing = len(cls.missing_translation_ids(lang))
            report[lang] = {
                "total": total,
                "translated": total - missing,
                "missing": missing,
            }
        return report

    @classmethod
    def _resolve_system_language(cls) -> str:
        locale = QLocale.system()
        bcp47 = (locale.bcp47Name() or "").strip()
        if bcp47.lower().startswith("zh-hant"):
            return "zh-Hant"
        if bcp47.lower().startswith("zh-hans"):
            return "zh-Hans"
        name = (locale.name() or "").strip().lower().replace("-", "_")
        if name.startswith("zh_tw") or name.startswith("zh_hk") or name.startswith("zh_mo"):
            return "zh-Hant"
        if name.startswith("zh_"):
            return "zh-Hans"
        base = (bcp47.split("-", 1)[0] or name.split("_", 1)[0]).lower()
        if base == "pt":
            if name.endswith("_pt"):
                return "pt-PT"
            return "pt-BR"
        if base == "es":
            if name.endswith("_es"):
                return "es-ES"
            return "es-419"
        if base in cls.SUPPORTED_LANGUAGES:
            return base
        return cls.DEFAULT_LANGUAGE

    def tr(self, source_text: str) -> str:
        source = self._KEY_TO_SOURCE.get(source_text, source_text)
        for lang in self._language_fallback_chain(self.effective_language()):
            translated = self._TRANSLATIONS.get(lang, {}).get(source)
            if translated is not None:
                return translated
            translated = self._EXTRA_TRANSLATIONS.get(lang, {}).get(source)
            if translated is not None:
                return translated
            translated = self._PROMPT_TEMPLATE_TRANSLATIONS.get(lang, {}).get(source)
            if translated is not None:
                return translated
        return source

    def plural(self, key_base: str, value: int) -> str:
        lang = self.effective_language()
        category = self._plural_category(lang, value)
        forms = None
        for candidate in self._language_fallback_chain(lang):
            forms = self._PLURAL_TEMPLATES.get(candidate, {}).get(key_base)
            if forms is not None:
                break
        if forms is None:
            forms = self._PLURAL_TEMPLATES["default"].get(key_base, {})
        template = forms.get(category) or forms.get("other") or self.tr(f"{key_base}.other")
        return self.tr(template)

    def effective_qlocale(self) -> QLocale:
        if self._mode == self.AUTO_MODE:
            return QLocale.system()
        lang = self.effective_language()
        locale = QLocale(lang.replace("-", "_"))
        if locale.language() != QLocale.Language.C:
            return locale
        system_name = QLocale.system().name()
        if "_" in system_name and "-" not in lang:
            region = system_name.split("_", 1)[1]
            fallback = QLocale(f"{lang}_{region}")
            if fallback.language() != QLocale.Language.C:
                return fallback
        return QLocale.system()

    def format_time(self, dt) -> str:
        # Time format should follow user's system regional preference (e.g. 24h),
        # independent from selected UI language.
        return QLocale.system().toString(dt.time(), QLocale.FormatType.ShortFormat)

    def format_short_date(self, dt) -> str:
        # Date format (order/separators) should follow system regional preference,
        # while date text (month/day names) should follow selected app language.
        system_locale = QLocale.system()
        text_locale = self.effective_qlocale()
        pattern = self._date_pattern_without_weekday(system_locale.dateFormat(QLocale.FormatType.LongFormat))
        if not pattern:
            pattern = system_locale.dateFormat(QLocale.FormatType.ShortFormat)
        return text_locale.toString(dt.date(), pattern)

    @staticmethod
    def _date_pattern_without_weekday(pattern: str) -> str:
        if not pattern:
            return pattern
        out: list[str] = []
        i = 0
        in_quote = False
        while i < len(pattern):
            ch = pattern[i]
            if ch == "'":
                if i + 1 < len(pattern) and pattern[i + 1] == "'":
                    out.append("''")
                    i += 2
                    continue
                in_quote = not in_quote
                out.append(ch)
                i += 1
                continue
            if not in_quote and ch == "d":
                j = i
                while j < len(pattern) and pattern[j] == "d":
                    j += 1
                count = j - i
                # d/dd = day number; ddd/dddd = localized weekday name.
                if count >= 3:
                    i = j
                    continue
                out.append("d" * count)
                i = j
                continue
            out.append(ch)
            i += 1

        cleaned = "".join(out)
        cleaned = re.sub(r"\s*,\s*", ", ", cleaned)
        cleaned = re.sub(r"\s{2,}", " ", cleaned).strip()
        cleaned = re.sub(r"^[,./\-\s]+", "", cleaned)
        cleaned = re.sub(r"[,./\-\s]+$", "", cleaned)
        cleaned = re.sub(r",\s*,", ",", cleaned)
        return cleaned.strip()

    @staticmethod
    def _language_fallback_chain(lang: str) -> tuple[str, ...]:
        if lang == "pt-PT":
            return ("pt-PT", "pt-BR")
        if lang == "es-ES":
            return ("es-ES", "es-419")
        return (lang,)

    @staticmethod
    def _plural_category(lang: str, value: int) -> str:
        n = abs(int(value))
        if lang in ("ru", "uk"):
            mod10 = n % 10
            mod100 = n % 100
            if mod10 == 1 and mod100 != 11:
                return "one"
            if 2 <= mod10 <= 4 and not 12 <= mod100 <= 14:
                return "few"
            if mod10 == 0 or 5 <= mod10 <= 9 or 11 <= mod100 <= 14:
                return "many"
            return "other"
        if lang == "sr":
            mod10 = n % 10
            mod100 = n % 100
            if mod10 == 1 and mod100 != 11:
                return "one"
            if 2 <= mod10 <= 4 and not 12 <= mod100 <= 14:
                return "few"
            return "other"
        if lang == "fr":
            return "one" if n in (0, 1) else "other"
        return "one" if n == 1 else "other"
